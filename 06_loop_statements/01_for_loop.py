## for variable in sequence

a=['harish',21,70.13,True]
for i in a:
    print(i)  #  it give out put line by line

#output:# harish
        # 21
        # 70.13
        # True

for i in range(1,30):
    print(i)     # it gives  1  to 29(30-1)  numbers outputs

for i in range(1,30,2):
    print(i)         # it gives it skip 2 steps and give output

for i in range(len(a)):
    print(i)            # here we get the indexing of a variable

