# Membership Operators  
# -Check if a value exists in a sequence.

name = 'harish mayakuntla'
print('h' in name)    # here use 'in'  ,'h' letter exits the given string,so statement is True
print('z' in name)    # here use 'in'  ,'z' letter does not exits the given string ,so statement is False

print('h' not in name) # here use ' not in '  ,'h' letter exits the given string , so statement is False
print('z' not in name) # here use ' not in '  ,'z' letter does not exits the given string ,so statement is True

number=20,50,30
print(50 in number)      # here use 'in'  , 50  number exits the given string , so statement is True
print(50 not in number)  # here use ' not in '  , 50  number exits the given string , so statement is False