# Bitwise Operators in Python

a = 5      # Binary: 0101
b = 3      # Binary: 0011

print("Value of a:", a)
print("Value of b:", b)

# Bitwise AND
print("\n1. Bitwise AND (&)")
print("a & b =", a & b)

# Bitwise OR
print("\n2. Bitwise OR (|)")
print("a | b =", a | b)

# Bitwise XOR
print("\n3. Bitwise XOR (^)")
print("a ^ b =", a ^ b)

# Bitwise NOT
print("\n4. Bitwise NOT (~)")
print("~a =", ~a)
print("~b =", ~b)

# Left Shift
print("\n5. Left Shift (<<)")
print("a << 1 =", a << 1)
print("b << 2 =", b << 2)

# Right Shift
print("\n6. Right Shift (>>)")
print("a >> 1 =", a >> 1)
print("b >> 1 =", b >> 1)