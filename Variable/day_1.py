# Variables can change
x = 10
print(x)
x = 20
print(x)

# Multiple variables in one line
a, b, c = 10, 20, 30
print(a)
print(b)
print(c)

# Same value to multiple variables
i = j = l = 100
print(i, j, l)

# Checking type of variable
x = 10
print(type(x))

# Dynamic typing(Python automatically changes type)
s = 10
s = "Hello"
s = 3.5

